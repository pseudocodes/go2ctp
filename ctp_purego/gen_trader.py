"""Regenerate the typed Go bindings in the CTP 6.7.13 header's virtual-slot order."""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LIB = ROOT.parent / "ctp/lib"
LINUX = LIB / "v6.7.13_20260225_api_traderapi_se_linux64/ThostFtdcTraderApi.h"
MAC = LIB / "v6.7.13_MacOS_20260529/ThostFtdcTraderApi.h"
BANNER = """// Code generated by gen_trader.py from ThostFtdcTraderApi.h. DO NOT EDIT.
//go:build (amd64 && (windows || linux || darwin)) || (arm64 && darwin)

package ctp_purego

import (
    "github.com/ebitengine/purego"
    "github.com/pseudocodes/go2ctp/thost"
)
"""


def methods(path, kind):
    text = re.sub(r"//[^\n]*|/\*.*?\*/", "", path.read_text(), flags=re.S)
    body = re.search(r"class\s+(?:TRADER_API_EXPORT\s+)?CThostFtdcTrader" + kind
                     + r"\s*\{(.*?)\n\};", text, re.S)[1]
    result = []
    for decl in re.findall(r"\bvirtual\s+([^;{}]+?\))\s*(?:=\s*0\s*;|\{)", body):
        ret, name, args = re.fullmatch(r"(void|int|const\s+char\s*\*)\s*(\w+)\s*\((.*)\)", decl.strip()).groups()
        params = []
        for param in filter(None, args.split(",")):
            typ, arg = re.fullmatch(r"(.+?[\s*])(\w+)", param.split("=")[0].strip()).groups()
            params.append((arg, re.sub(r"\s+", "", typ)))
        result.append((name, re.sub(r"\s+", "", ret), params))
    if len(result) != len(re.findall(r"\bvirtual\s", body)):
        raise ValueError(f"unparsed virtual declaration in {path}")
    return result


def go_type(c, native=True):
    types = {"void": "", "int": "int32" if native else "int", "bool": "uint8" if native else "bool",
             "char*": "string", "constchar*": "string", "THOST_TE_RESUME_TYPE": "thost.THOST_TE_RESUME_TYPE",
             "CThostFtdcTraderSpi*": "*traderSPI"}
    if c in types:
        return types[c]
    if re.fullmatch(r"CThostFtdc\w+Field\*", c):
        return "*thost." + c[:-1]
    raise ValueError(f"unrecognised SDK type {c}")


def check_go_method_order(kind, methods):
    # Go interface satisfaction only checks the method set, not declaration order.
    text = (ROOT.parent / "thost/traderapi.go").read_text()
    body = re.search(r"^type Trader" + kind + r" interface \{(.*?)^\}", text, re.M | re.S)[1]
    names = re.findall(r"^\s*(\w+)\(", body, re.M)
    expected = [name for name, _, _ in methods]
    if kind == "Api":
        # The native factory is a Go constructor; GetApiVersion is exposed on the interface.
        expected.insert(0, "GetApiVersion")
    if names != expected:
        raise ValueError(f"thost.Trader{kind} method names or declaration order differ from {LINUX.name}")


def generate(api, spi):
    out = [BANNER, f"const traderMethodCount = {len(api)}\nconst traderCallbackCount = {len(spi)}",
           "type traderMethods struct {"]
    for name, ret, args in api:
        signature = ", ".join(["*traderObject"] + [go_type(t) for _, t in args])
        out.append(f"{name} func({signature}) {go_type(ret)}")
    out += ["}", "func (m *traderMethods) bind(v *[traderMethodCount]uintptr) {",
            "slots := [traderMethodCount]any{"]
    out += [f"&m.{name}," for name, _, _ in api]
    out += ["}", "for i, target := range slots { purego.RegisterFunc(target, v[i]) }", "}"]
    for name, ret, args in api:
        if name in ("Release", "RegisterSpi", "SubscribePrivateTopic"):
            continue
        signature = [f"{n} {go_type(t, False)}" for n, t in args]
        if name == "ReqUserLogin":
            signature.append("_ ...any")  # Legacy thost interface, not part of the native ABI.
        params = ["a.obj"] + [f"int32({n})" if t == "int" else n for n, t in args]
        call = f"a.methods.{name}({', '.join(params)})"
        if ret == "int":
            call = f"int({call})"
        out += [f"func (a *TraderApi) {name}({', '.join(signature)}) {go_type(ret,False)} {{",
                ("return " if ret != "void" else "") + call, "}"]
    out += ["func makeTraderCallbacks() [traderCallbackCount]uintptr {",
            "return [traderCallbackCount]uintptr{"]
    for name, _, args in spi:
        types = [t for _, t in args]
        if name == "OnFrontConnected":
            callback = """purego.NewCallback(func(this *traderSPI) uintptr {
                if s := traderReceiver(this); s != nil { s.OnFrontConnected() }; return 0 })"""
        elif name == "OnRspError":
            callback = """purego.NewCallback(func(this *traderSPI, info *thost.CThostFtdcRspInfoField, id int32, last uint8) uintptr {
                if s := traderReceiver(this); s != nil { s.OnRspError(info, int(id), last != 0) }; return 0 })"""
        else:
            if types == ["int"]:
                helper = "traderIntCallback"
            elif len(types) == 1 and types[0].endswith("Field*"):
                helper = "traderNotification"
            elif len(types) == 2 and types[1] == "CThostFtdcRspInfoField*":
                helper = "traderErrorReturn"
            elif types[1:] == ["CThostFtdcRspInfoField*", "int", "bool"]:
                helper = "traderResponse"
            else:
                raise ValueError(f"unrecognised callback {name}{types}")
            callback = f"{helper}(thost.TraderSpi.{name})"
        out.append(callback + ",")
    out += ["}", "}", "// BaseTraderSpi can be embedded to override only the events of interest.",
            "type BaseTraderSpi struct{}", "var _ thost.TraderSpi = BaseTraderSpi{}"]
    for name, _, args in spi:
        signature = ", ".join(go_type(t, False) for _, t in args)
        out.append(f"func (BaseTraderSpi) {name}({signature}) {{}}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    api, spi = (methods(LINUX, k) for k in ("Api", "Spi"))
    for kind, linux in (("Api", api), ("Spi", spi)):
        check_go_method_order(kind, linux)
        if methods(MAC, kind) != linux:
            raise ValueError(f"{kind} differs between the macOS and Linux SDKs")
    source = generate(api, spi)
    # Separate declarations, keep list entries and statements on adjacent lines.
    source = source.replace("\nfunc ", "\n\nfunc ").replace("\ntype ", "\n\ntype ")
    path = ROOT / "trader_bindings.go"
    path.write_bytes(subprocess.check_output(["gofmt"], input=source.encode()))
